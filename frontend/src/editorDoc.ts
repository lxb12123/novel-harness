// 磁盘上那一章变了，编辑器里那份要不要跟着换。**纯判断**（同 `continuation.ts` 的分法）。
//
// ── 它为什么突然需要存在 ─────────────────────────────────────────────────
//
// 编辑器原来的规矩是一行：「重取到什么就 setDoc 什么」。那条规矩成立的前提写在
// `PUT /chapters/{n}/text` 的 docstring 里——**「作者改的就是他眼前那份，中间没有第三方」**。
//
// 2026-08-11 起有第三方了：写作助手起草**直接写进磁盘上那一章**（ADR 0021，不弹框）。
// 于是那一行会静默吃掉作者没保存的字——他一边打字一边跟助手说话，助手写了一稿进同一章，
// 重取一次，他刚打的半段就没了。**而没保存过的东西哪儿都找不回来**：版本历史只存保存过的。
//
// 反过来「干脆不重取」也不行：那样作者屏幕上是一份旧稿，他一按保存就把助手写的那一整章
// 盖掉（那一版还在历史里，所以是可恢复的——两种错的代价不对称，这个判断按不对称的那侧写）。

/** 三态。**「一样」必须和「要换」分开**：作者在同一份磁盘正文上改了字也是「不一样」，
 *  但那是他自己改的，不是别人动的——分不开就会在他自己打字的时候弹一句别人改过。 */
export type DiskChange = "same" | "adopt" | "warn";

/**
 * @param disk   这一次从磁盘读回来的正文
 * @param loaded 编辑器手上这份的**出处**（上一次采纳的那一版原文）；从没读到过就是 `null`
 * @param dirty  作者有没有还没保存的字
 */
export function diskChange(disk: string, loaded: string | null, dirty: boolean): DiskChange {
  // **先比出处，再看脏态**——顺序反过来的话，作者一边打字一边重取就会被告知「别处改过」。
  if (disk === loaded) return "same";
  // **还没有出处 = 这一章的正文还没装过 ⇒ 一律采纳。**
  //
  // 2026-08-13 作者在真书上撞到的假警报就漏在这一档：他在某一章敲了字没保存，
  // 换到另一章，新那章弹「这一章在别处变过了……现在按保存会盖过它」——
  // 而那一章**根本没人动过**（实测：接口给的和磁盘上的逐字节相同）。
  //
  // 根因是 `dirty` 这一位**属于上一章**：换章时编辑器把出处清成 `null`，可作者
  // 那点没保存的字是上一章的，跟这一章毫无关系。拿它去判「这一章被别处改过」
  // 是拿一个不相干的事实下结论。
  //
  // **这一档为什么安全**（`loaded === null` ⇒ 采纳，不怕吃掉作者的字）：
  // 编辑器手上根本没有这一章的正文，没有任何属于这一章的字会被盖掉。
  //
  // ⚠️ **这句假警报比烦人更坏**：它说的是一句关于作者稿子安全的话，说多了他就学会
  // 忽略它 —— 等哪天写作助手真的写进了那一章、这句话是真的时候，那道退路已经废了。
  if (loaded === null) return "adopt";
  if (dirty) return "warn";
  return "adopt";
}
