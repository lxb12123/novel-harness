-- 016：一条规矩**管到什么时候**，由模型自己写下来，跟规矩存在一起。
--
-- ── 为什么这一列必须存在 ──────────────────────────────────────────────────
--
-- [ADR 0028](../../../docs/adr/0028-rules-expire-by-situation.md) 把规矩的有效期从
-- 「按章号算」换成「模型按情境判」。落地时那句提示是**通用的**：
--
--     （作者写第 722 章时随口说的；情境不在了就不必守）男主在这片沙地不杀人
--
-- 「情境」指哪个情境？靠模型每一轮从那句话里自己读出来。**它读得出来，但没留下任何
-- 可以回头看的东西** —— 作者问「我写第 700 章那阵子跟它交代过什么、那些话还管着吗」，
-- 今天答不上来：规矩只活在下一轮的 prompt 里，不进日志、不进任何屏幕。
--
-- 作者 2026-08-15 的原话：「你在写某一章的时候用户讲过的规则，然后**你规定的时效**
-- 什么的都可以记一下」。**「你规定的」这三个字把设计定死了**：时效得是模型明确交出来的
-- 一个字段，不能埋在规矩正文里——埋在句子里就没有「可以记一下」的东西。
--
-- ── 为什么是一列文本，不是一个枚举 ────────────────────────────────────────
--
-- 「男主走出这片沙地为止」枚举不出来。想枚举就得先回答「这是哪一类时效」——那是语义
-- 判断，ADR 0005 不许引擎做。**所以它是模型用作者的话写下的一句人话，引擎一个字都不解析**：
-- 存进去、渲进 prompt、摆进表格，三处都原样搬。
--
-- ── 为什么不是新开一张 `author_rule` 表 ───────────────────────────────────
--
-- 规矩是 canonical 历史里的一条 SYSTEM 消息（`agent/rules.py` 顶上写着为什么：
-- **秘密一旦交出去就在持久化的东西里了，每多一个落盘面就多一处要单独去搜的地方**）。
-- 时效是那条消息的一个属性，跟着它走，跟着它一起被 `ChatStore` 逐字段落盘、逐字段读回，
-- 「读回来逐字节相同」那条不变量一个字都不用改。新开一张表 = 新开一个落盘面 +
-- 一份要和历史对齐的下标。
--
-- 空串 = 这条消息不是规矩，或者它是 016 之前记下的（那时模型还没有这个参数）。
-- **老规矩不补写**：给它编一个时效就是替模型说它没说过的话。渲染那一层认这个空串
-- （`rules.prompt_text` 退回 0028 那句通用的），表格那一层照实说「没记下」。
ALTER TABLE chat_message ADD COLUMN rule_until TEXT NOT NULL DEFAULT '';

