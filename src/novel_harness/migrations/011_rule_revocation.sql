-- 作者撤销一条自己定下的规矩。
--
-- ADR 0023 的退路押在两件事上：「**看得见** + **能取消**」。读端（`rules.live_rules()`）
-- 落地那天就有了，**取消一直缺着** —— 也就是那条退路只兑现了一半。
--
-- ── 为什么是「追加一条撤销」而不是「把那条删掉/改掉」 ──────────────────
-- canonical **只增不改**，那是 3.4 的核心不变量：从库里读回来重建出的 `Conversation`
-- 必须和存进去之前那个**逐字节相同**，否则 resume 之后模型看到的是另一段历史
-- ——而且没有任何东西会报错。删一行就把这条不变量拆了。
--
-- ── 为什么不能靠「再说一遍」来表达撤销 ─────────────────────────────────
-- 这套规矩靠「**同一句说第二遍 = 从批级升到章级**」来放宽（ADR 0023 决策二）。
-- 撤销要是也走文本，两者在同一条通路上就分不开了：作者想取消，系统听成了加强。
-- 所以撤销必须有一个**结构上的**槽，而不是一段字。
--
-- 值 = 被撤销的那条消息在**同一段会话里**的 `seq`（`UNIQUE(session_id, seq)` 保证它唯一）。
-- NULL = 这条消息不撤销任何东西（绝大多数）。
--
-- 没有加复合外键指向 `(session_id, seq)`：SQLite 的 `ADD COLUMN` 加不了那个约束，
-- 而为它重建整张表的代价远大于收益 —— seq 只在本会话内有意义，而 session 已经有外键。
ALTER TABLE chat_message ADD COLUMN revokes_seq INTEGER
  CHECK (revokes_seq IS NULL OR revokes_seq >= 0);

