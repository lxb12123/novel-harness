-- 作者改一条滚动总结（改 / 撤回）时，机器写的那一行**不许凭空消失**。
--
-- 照 005_fact_edit.sql 的先例。那份文件确立的调子在这儿一字不改地适用：
-- 图是 append-only 的，「作者改一条事实 = 一行凭空消失」是全库唯一一处，
-- 而滚动总结**真的在花作者的钱、真的在影响每一稿**（`draft/product_assemble.py`
-- 把它们一行行拼进起草 prompt），它更不该是例外。
--
-- 所以：**改 = 追加一行作者版；删 = 追加一行标记撤回。** 原来那条模型生成的留着。
--
-- ── 为什么是两列而不是一列 ────────────────────────────────────────────────
--
-- `source` 回答「这段字是谁写的」，`status` 回答「它这会儿算不算数」。合成一列
-- （比如一个四值的 kind）会让「作者撤回一条**他自己写的**总结」表达不出来——
-- 而那是撤回按钮最常被按的那一档（写错了，先撤掉再说）。
--
-- ── 唯一键那一关：为什么不用重建表 ────────────────────────────────────────
--
-- 现有 `UNIQUE (project_id, chapter_number, schema_version, prompt_hash)` 是
-- **内容寻址**的（004 的原话：「同一章同一 prompt 只付一次调用」）。新长出来的两种行
-- 各自有自己的内容地址，`prompt_hash` 那一列照装，一张表都不用重建：
--
--   模型版   sha256(那次 prompt 的消息序列)          ← 004 起就是这么存的，一个字节没动
--   作者版   sha256(作者自己那段文字 + 它是第几次改)
--   撤回     sha256(被撤的那一行的地址 + 它是第几次改)
--
-- 「它是第几次改」（= 插进去之前这一章已经有几行）也算进地址里，是因为**位置也是内容**：
-- 只哈希文字的话，作者「改成 A → 改成 B → 改回 A」的第三步会撞上第一步那一行的键，
-- 而库里那一行是**旧的**——最新一行仍然是 B，于是屏幕上他刚做的那次修改什么都没发生，
-- 而且不报错。同一个形状在「撤回之后再点重新生成」上会再犯一次
-- （同一章正文 = 同一份 prompt = 同一个哈希）。判据写在
-- `draft/rolling_summary.py::_address`，两头都有测试钉着。
--
-- ── 读端的语义（`draft/rolling_summary.py`）────────────────────────────────
--
-- 「这一章现在的总结」= **最新那一行**（rowid 最大）。它 RETRACTED 就当这一章没有：
-- 起草时不带它、`coverage()` 里算作缺、想重来就再点生成。
-- 「删了重来」因此顺带覆盖，不用做两套。
ALTER TABLE chapter_summary
  ADD COLUMN source TEXT NOT NULL DEFAULT 'model'
  CHECK (source IN ('model', 'author'));

ALTER TABLE chapter_summary
  ADD COLUMN status TEXT NOT NULL DEFAULT 'ACTIVE'
  CHECK (status IN ('ACTIVE', 'RETRACTED'));

