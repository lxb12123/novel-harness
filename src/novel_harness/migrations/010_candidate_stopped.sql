-- 一稿没写完就停下来了 —— 而它仍然值得留着。
--
-- ── 为什么留 ────────────────────────────────────────────────────────────
-- 按停那一刻已经生成的 token 是**付过钱的信息**。扔掉 = 钱花了字没了。
-- 而 ADR 0022 把起草做成了「提议」而不是「落盘」，所以半截的一稿只是**短一点的提议**，
-- 它本来就不会自动进书 —— 留着零风险。
-- 大厂的做法一致：Claude Code 按 Esc 保留到那一刻为止的全部内容并标注
-- `[Request interrupted by user]`；Messages API 用 `stop_reason` 说明为什么停。
--
-- ── 为什么必须**标注**，而不是默默留着 ─────────────────────────────────
-- 对作者，显然。**真正要命的是对模型那一半**：
-- 一段断在半句的正文，模型下次读到它、若不知道那是被砍断的，
-- **会把那个断口当成一种有意的写法去模仿**。
-- 「他缓缓抬起手，然后——」在代码里一眼就是坏的；在小说里它读起来像一个刻意的悬停。
-- 这个陷阱是写作工具独有的，所以这一列不是元数据，是**语义的一部分**：
-- 按 id 读回这一稿时，这个标注必须跟着一起回来。
--
-- NULL = 它写完了。非空 = 没写完，值说明为什么（作者按停 / 端点断了 / …）。
-- **开放字符串，不 CHECK**：同 `decisions.DecisionKind` 和 `EdgeSource` 的取舍——
-- 它不参与任何过滤分支，而 SQLite 改 CHECK 要重建整张表。
ALTER TABLE draft_candidate ADD COLUMN stopped_reason TEXT;

