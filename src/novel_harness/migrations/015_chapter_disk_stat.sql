-- 015：记下每一章文件的 (mtime, size)，好让「有没有改过」这个问题只 stat 不读盘。
--
-- ── 为什么要这两列 ────────────────────────────────────────────────────────
--
-- 2026-08-14 起「把库和磁盘对一遍」这件事从**作者点一颗按钮**变成**他每次切回标签页
-- 就自动做**（三层方案第二层）。一个每天触发几十次的动作，代价必须接近零。
--
-- 而在这两列之前，「有没有改过」的唯一答案是 `text_sha256`，算它就得**把 722 个文件
-- 全读一遍**。实测那本真书：整条 sync（一个字没改）66ms，其中读+算哈希只占 ~10ms，
-- 剩下 ~56ms 是 722 次切章解析 + 722 次库查找——**而 stat 说「没变」时这一整串都能跳掉**。
-- 实测降到 ~1–2ms，且这个差距随书长线性拉大（3000 章的书那边是 ~280ms）。
--
-- 这是 Git 的 index 用了二十年的那一招：存 stat 信息，`git status` 先 stat，
-- 一致就信缓存，**只有对不上才去读文件算 sha**。
--
-- ── 它们**不是**真相，`text_sha256` 才是 ───────────────────────────────────
--
-- **mtime 会撒谎**：`rsync -t` / `cp -p` / 从备份恢复 / 某些编辑器都可能保留原 mtime。
-- 如果同时大小又没变，那次改动 stat 这一关就漏了（Git 自己也有这个病，就是那个
-- 著名的 "racy git"）。
--
-- 所以这两列**只是快路的过滤器**：stat 一致 ⇒ 假定没变；stat 不一致 ⇒ 读文件算 sha，
-- 由 sha 裁决。而漏掉的那一档由**开书时那一次全量 read+hash** 兜住（66ms，一次）。
--
-- ── 可空是有意的 ──────────────────────────────────────────────────────────
--
-- 老库里已有的行是 NULL = **「不知道这一章的 stat」⇒ 必须重读**。这是 fail-safe 的
-- 那一侧（多读一次，无害），而且它自愈：读过一次就填上了。
-- 反过来给个默认值 0 的话，第一次检查会把整本书判成「和记录一致」——**一本刚升级
-- 的库会安静地停止对齐**，而屏幕上没有任何东西说得出来。

ALTER TABLE chapter ADD COLUMN disk_mtime_ns INTEGER;
ALTER TABLE chapter ADD COLUMN disk_size INTEGER;
